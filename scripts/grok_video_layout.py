def head(lang, slug, c):
    """共用 head，再追加视频组件样式表"""
    h = G.head(lang, slug, c)
    css = f'<link rel="stylesheet" href="/assets/models/grok-image.css?v={G.VER}">'
    return h.replace(css, css + f'\n<link rel="stylesheet" href="/assets/models/grok-video.css?v={VER}">', 1)


def vid(name, lang, mode='play', eager=False):
    """mode='play'：有控制条，点开播放；mode='loop'：静音自动循环（首屏、对比区），减少动态时由 JS 暂停"""
    w, h, audio, zh, en = VIDS[name]
    label = html.escape(zh if lang == 'zh' else en, quote=True)
    poster = f'{MEDIA}/{name}.webp?v={VER}'
    src = f'{MEDIA}/{name}.mp4?v={VER}'
    if mode == 'loop':
        return (f'<video src="{src}" poster="{poster}" width="{w}" height="{h}" autoplay muted loop playsinline '
                f'preload="{"auto" if eager else "metadata"}" aria-label="{label}" data-gv-loop></video>')
    return (f'<video src="{src}" poster="{poster}" width="{w}" height="{h}" controls playsinline preload="none" '
            f'aria-label="{label}"></video>')


def still(name, alt):
    w, h = STILLS[name]
    return (f'<img src="{MEDIA}/{name}.webp?v={VER}" width="{w}" height="{h}" alt="{html.escape(alt, quote=True)}" '
            f'loading="lazy" decoding="async">')


# ---------------- 首屏 ----------------
def hero(lang, slug, c):
    t = G.L[lang]
    facts = ''.join(f'<li>{k} <strong>{v}</strong></li>' for k, v in c['facts'])
    crumbs = f'<li><a href="/">{t["home"]}</a></li><li><a href="/{lang}/models/">{t["hub"]}</a></li>'
    if slug != HUB:
        crumbs += f'<li><a href="/{lang}/models/{HUB}">{t["series"]}</a></li>'
    crumbs += f'<li aria-current="page">{c["crumb"]}</li>'
    notice = f'      <p class="o-notice" role="note">{c["notice"]}</p>{NL}' if c.get('notice') else ''
    name = c['hero_vid']
    cap = VIDS[name][3] if lang == 'zh' else VIDS[name][4]
    return f'''  <!-- Hero -->
  <section class="gk-hero" aria-labelledby="hero-title">
    <div class="o-wrap">
      <nav aria-label="{t['crumbs']}">
        <ol class="o-crumbs">{crumbs}</ol>
      </nav>
      <p class="gk-kicker">{G.logo(22)}<span>{c['kicker']}</span></p>
      <h1 class="gk-h1" id="hero-title">{c['h1']}</h1>
      <p class="gk-lead">{c['lead']}</p>
{notice}      <div class="o-cta">
        <a class="o-btn o-btn-dark" href="{REG}">{t['get_key']}</a>
        <a class="o-btn o-btn-light" href="#pricing">{t['see_price']}</a>
      </div>
      <ul class="o-facts" aria-label="{t['facts_label']}">{facts}</ul>
      <figure class="gv-hero">
        {vid(name, lang, 'loop', eager=True)}
        <figcaption>{html.escape(cap, quote=False)} · {c['hero_cap']}</figcaption>
      </figure>
    </div>
  </section>

'''


# ---------------- 系列一览（总览页） ----------------
def lineup(lang, c):
    t = G.L[lang]
    lis = ''
    for s, tag, h, p, pts in c['lineup']:
        m = MODELS[s]
        tg = f'<span class="gk-tag">{tag}</span>' if tag else ''
        li = ''.join(f'<li>{x}</li>' for x in pts)
        frm = ('' if lang == 'zh' else 'from ')
        lis += (f'        <li class="gk-model o-reveal">{tg}<h3><a href="/{lang}/models/{s}">{h}</a></h3><code>{s}</code><p>{p}</p>'
                f'<ul>{li}</ul><p class="gk-model-price">{frm}<strong>{price(lang, m["usd"])}</strong> / {t["per"]}{" 起" if lang == "zh" else ""}</p></li>{NL}')
    return G.section('models', c['about_h2'], f'      <ul class="gk-models">{NL}{lis}      </ul>{NL}', c.get('about_lead', ''))


# ---------------- 能力 ----------------
def features(lang, c):
    lis = ''
    for i, (src, h, p) in enumerate(c['features']):
        if src:
            art = f'<div class="gk-feature-img gv-frame">{vid(src, lang)}</div>'
            cls = 'gk-feature'
        else:
            art = f'<div class="gk-feature-num" aria-hidden="true">{i + 1:02d}</div>'
            cls = 'gk-feature gk-feature-text'
        lis += f'        <li class="{cls} o-reveal">{art}<div class="gk-feature-body"><h3>{h}</h3><p>{p}</p></div></li>{NL}'
    return G.section('features', c['features_h2'], f'      <ul class="gk-features">{NL}{lis}      </ul>{NL}', c.get('features_lead', ''), band=True)


# ---------------- 改视频对比（原视频 → 两个结果） ----------------
def edits(lang, c):
    rows = ''
    for title, items in c['edit_rows']:
        cells = ''.join(f'<li><figure>{vid(n, lang, "loop")}<figcaption><b>{lab}</b>{html.escape(VIDS[n][3] if lang == "zh" else VIDS[n][4], quote=False)}</figcaption></figure></li>'
                        for n, lab in items)
        rows += f'      <h3 class="gk-h3 o-reveal">{title}</h3>{NL}      <ul class="gv-trio o-reveal">{cells}</ul>{NL}'
    return G.section('edits', c['edits_h2'], rows + f'      <p class="o-note">{c["edits_note"]}</p>{NL}', c['edits_lead'])


# ---------------- 示例视频 ----------------
def gallery(lang, c):
    t = G.L[lang]
    lis = ''
    for n, tag in c['gallery']:
        cap = VIDS[n][3] if lang == 'zh' else VIDS[n][4]
        lis += f'        <li class="gv-shot o-reveal"><figure>{vid(n, lang)}<figcaption><b>{tag}</b>{html.escape(cap, quote=False)}</figcaption></figure></li>{NL}'
    inner = (f'      <ul class="gv-gallery">{NL}{lis}      </ul>{NL}'
             f'      <p class="o-note">{t["credit"]} <a href="{XAI_API}" target="_blank" rel="noopener">{t["credit_link"]}</a></p>{NL}')
    return G.section('gallery', c['gallery_h2'], inner, c['gallery_lead'])


# ---------------- 使用场景：用视频封面帧做配图（静态图，不加载视频） ----------------
def uses(lang, c):
    lis = ''
    for n, k, h, p in c['uses']:
        art = ''
        if n:
            w, hh, _, zh, en = VIDS[n]
            art = (f'<div class="gk-use-img"><img src="{MEDIA}/{n}.webp?v={VER}" width="{w}" height="{hh}" '
                   f'alt="{html.escape(zh if lang == "zh" else en, quote=True)}" loading="lazy" decoding="async"></div>')
        lis += f'        <li class="gk-use o-reveal">{art}<div class="gk-use-body"><span class="gk-k">{k}</span><h3>{h}</h3><p>{p}</p></div></li>{NL}'
    return G.section('use-cases', c['uses_h2'], f'      <ul class="gk-uses">{NL}{lis}      </ul>{NL}', c.get('uses_lead', ''), band=True)


# ---------------- 价格（按秒） ----------------
def pricing(lang, slug, c):
    t = G.L[lang]
    bill = ''.join(f'<li><strong>{a}</strong>{b}</li>' for a, b in c['billing'])
    th = ''.join(f'<th scope="col"{" class=\"o-num\"" if i >= 1 else ""}>{x}</th>' for i, x in enumerate(t['th']))
    body = ''
    for s, group in c['price_rows']:
        cur = 'gk-cur' if s == slug else ''
        trs = ''
        for res, usd, off in TIERS[s]:
            trs += (f'            <tr class="{cur}"><th scope="row">{res}</th><td class="o-num o-hl">{price(lang, usd)} / {t["per"]}</td>'
                    f'<td class="o-num">{money(lang, usd, 5)}</td><td class="o-num">{money(lang, usd, 10)}</td>'
                    f'<td class="o-num gk-off">{price(lang, off)} / {t["per"]}</td></tr>{NL}')
        extra = []
        if s in INPUT_IMG:
            extra.append(c['in_img'].format(p=price(lang, INPUT_IMG[s][0])))
        if s in INPUT_VID:
            extra.append(c['in_vid'].format(p=price(lang, INPUT_VID[s][0])))
        sub =f'<small class="gv-in">{("；" if lang == "zh" else "; ").join(extra)}</small>' if extra else ''
        body += (f'          <tbody>{NL}            <tr class="gk-group"><th scope="rowgroup" colspan="5">{group} <code>{s}</code>{sub}</th></tr>{NL}'
                 f'{trs}          </tbody>{NL}')
    costs = ''.join(f'''        <li class="o-cost o-reveal">
          <h4>{h}</h4>
          <p class="o-cost-calc">{calc}</p>
          <p class="o-cost-total">{tot}</p>
          <p class="o-cost-off">{off}</p>
        </li>{NL}''' for h, calc, tot, off in c['costs'])
    inner = f'''      <ul class="o-billing o-reveal" aria-label="{c['pricing_h2']}">{bill}</ul>
      <div class="o-table-wrap o-reveal">
        <table class="o-table">
          <caption class="o-sr">{t['table_caption']}</caption>
          <thead><tr>{th}</tr></thead>
{body}        </table>
      </div>
      <p class="o-note">{c['price_note']}</p>
      <h3 class="gk-h3 o-reveal">{t['costs_h3']}</h3>
      <p class="o-note">{t['costs_note']}</p>
      <ul class="o-costs">
{costs}      </ul>
      <div class="o-price-cta o-reveal">
        <a class="o-btn o-btn-dark" href="{REG}">{t['get_key']}</a>
        <a class="o-btn o-btn-light" href="{PRICING}">{t['market_btn']}</a>
      </div>
'''
    return G.section('pricing', c['pricing_h2'], inner, c['pricing_lead'])


def money(lang, usd, sec, extra='0'):
    """sec 秒视频（另加 extra 美元）的总价：中文 ¥ 两位小数，英文 $ 三位小数"""
    v = float(usd) * sec + float(extra)
    return f'¥{v * RATE:.2f}' if lang == 'zh' else f'${v:.3f}'
