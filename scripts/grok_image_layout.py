def price(lang, usd):
    """页面显示的单价：中文 ¥，英文 $"""
    return f'¥{cny(usd)}' if lang == 'zh' else f'${usd}'


def official(lang, m):
    """xAI 官方每张价格区间"""
    if not m['official_lo']:
        return L[lang]['retired']
    lo, hi = m['official_lo'], m['official_hi']
    f = (lambda x: f'¥{cny(x)}') if lang == 'zh' else (lambda x: f'${x}')
    return f(lo) if lo == hi else f'{f(lo)}–{f(hi)}'


def img(name, lang, eager=False, cls='', alt=None):
    w, h, zh, en = IMG[name]
    a = alt if alt is not None else (zh if lang == 'zh' else en)
    load = 'fetchpriority="high"' if eager else 'loading="lazy"'
    c = f' class="{cls}"' if cls else ''
    return (f'<img{c} src="/assets/models/{ASSET}/{name}.webp?v={VER}" width="{w}" height="{h}" '
            f'alt="{html.escape(a, quote=True)}" {load} decoding="async">')


def text(h):
    t = re.sub(r'<[^>]+>', '', h)
    return html.unescape(re.sub(r'\s+', ' ', t)).strip()


def page_url(lang, slug):
    return f'{SITE}/{lang}/models/{slug}'


