def family(lang, slug, items, h2, lead):
    lis = []
    for s, tag, title, sub in items:
        cur = ' aria-current="page"' if s == slug else ''
        tg = f'<span class="o-tag">{tag}</span>' if tag else ''
        lis.append(f'        <li><a href="/{lang}/models/{s}"{cur}>{tg}<b>{title}</b><span>{sub}</span></a></li>')
    inner = f'      <ul class="o-family o-reveal">{NL}' + NL.join(lis) + f'{NL}      </ul>{NL}'
    return f'  <!-- FAMILY -->{NL}' + section('family', h2, inner, lead, col=True)


def faq(c):
    items = ''.join(f'        <details{" open" if i == 0 else ""}><summary><h3>{q}</h3></summary><div class="o-ans"><p>{a}</p></div></details>{NL}'
                    for i, (q, a) in enumerate(c['faqs']))
    return f'''  <!-- FAQ -->
  <section class="o-section" id="faq" aria-labelledby="faq-title">
    <div class="o-wrap o-col">
      <h2 class="o-h2 o-reveal" id="faq-title">{c['faq_h2']}</h2>
      <div class="o-faq">
{items}      </div>
    </div>
  </section>

'''


