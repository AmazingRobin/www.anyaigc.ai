def ratios(lang, c):
    """同一画面在不同宽高比下的重构（xAI 官方 Smart resize 示例）"""
    lis = ''.join(f'        <li><figure>{img("resize-" + r.replace(":", "x"), lang, alt=c["ratio_alt"].format(r=r))}<figcaption>{r}</figcaption></figure></li>{NL}'
                  for r in ('1:2', '9:16', '3:4', '1:1', '16:9', '2:1'))
    chips = ''.join(f'<li>{r}</li>' for r in c['ratio_list'])
    inner = (f'      <ul class="gk-ratios o-reveal" tabindex="0" aria-label="{c["ratio_h2"]}">{NL}{lis}      </ul>{NL}'
             f'      <ul class="gk-chips o-reveal" aria-label="aspect_ratio">{chips}</ul>{NL}')
    return section('ratios', c['ratio_h2'], inner, c['ratio_lead'])


