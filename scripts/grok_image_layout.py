def uses(lang, c):
    lis = ''.join(f'        <li class="gk-use o-reveal">' + (f'<div class="gk-use-img">{img(n, lang)}</div>' if n else '')
                  + f'<div class="gk-use-body"><span class="gk-k">{k}</span><h3>{h}</h3><p>{p}</p></div></li>{NL}'
                  for n, k, h, p in c['uses'])
    return section('use-cases', c['uses_h2'], f'      <ul class="gk-uses">{NL}{lis}      </ul>{NL}', c.get('uses_lead', ''), band=True)


def why(c):
    lis = ''.join(f'        <li class="o-reveal"><h3>{h}</h3><p>{p}</p></li>{NL}' for h, p in c['why'])
    return section('why', c['why_h2'], f'      <ul class="gk-why">{NL}{lis}      </ul>{NL}')


# ---------------- 快速开始 ----------------
def quickstart(lang, c):
    t = L[lang]
    steps = ''.join(f'<li>{s}</li>' for s in c['steps'])
    tabs = ''.join(f'        <li role="presentation"><button type="button" role="tab" id="tab-{k}" aria-controls="panel-{k}" aria-selected="{"true" if i == 0 else "false"}">{name}</button></li>{NL}'
                   for i, (k, name, _, _) in enumerate(c['tabs']))
    panels = ''.join(f'''      <figure class="o-code" id="panel-{k}" role="tabpanel" aria-labelledby="tab-{k}">
        <figcaption><b>{cap}</b><button class="o-copy" type="button" aria-controls="code-{k}" data-done="{t['copied']}">{t['copy']}</button></figcaption>
<pre id="code-{k}"><code>{hl(code)}</code></pre>
      </figure>{NL}''' for k, _, cap, code in c['tabs'])
    inner = (f'      <ol class="o-steps o-reveal">{steps}</ol>{NL}'
             f'      <ul class="o-tabs" role="tablist" aria-label="{t["code_label"]}">{NL}{tabs}      </ul>{NL}{panels}'
             f'      <p class="o-note">{c["qs_note"]}</p>{NL}')
    return section('quickstart', c['qs_h2'], inner, band=True)


