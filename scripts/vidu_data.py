def flat(label_zh, label_en, amount, unit_zh="秒", unit_en="second"):
    """A flat per-unit rate."""
    return dict(label_zh=label_zh, label_en=label_en, amount=amount, unit_zh=unit_zh, unit_en=unit_en)


def step(label_zh, label_en, first, add, second=None):
    """Q2 tiered per-second rate: first second, optional 2-second total, then +add per second."""
    if second:
        text_zh = f"第1秒 ${first}，第2秒 ${second}，第3秒起每秒 +${add}"
        text_en = f"${first} for 1st second, ${second} for 2 seconds, then +${add}/s"
    else:
        text_zh = f"第1秒 ${first}，之后每秒 +${add}"
        text_en = f"${first} for 1st second, then +${add}/s"
    return dict(label_zh=label_zh, label_en=label_en, amount=first, first=first, second=second, add=add,
                text_zh=text_zh, text_en=text_en, unit_zh="视频", unit_en="video")


def addon(label_zh, label_en, amount):
    return dict(label_zh=label_zh, label_en=label_en, amount=amount, unit_zh="次", unit_en="task", addon=True)


def clip_cost(p, seconds):
    """Cost of one clip of `seconds` seconds for a step() or flat() price."""
    if "first" not in p:
        return Decimal(p["amount"]) * seconds
    first, add = Decimal(p["first"]), Decimal(p["add"])
    if p["second"]:
        if seconds == 1:
            return first
        return Decimal(p["second"]) + add * (seconds - 2)
    return first + add * (seconds - 1)


